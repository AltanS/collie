// THE ICON KEYS. Every glyph the app draws is named here by what it MEANS, not by its shape: `close`,
// `remove` and `status-failed` are three keys even where the default set draws all three as an X, so a
// glyph set (a theme's `glyphs`, ADR 0137) can tell them apart. One row per key: its meaning in plain
// words, the area of the app it shows in, and the lucide glyph the default set draws (`lucide.ts`
// holds the components, and `keys.test.ts` holds the two files to the same names).
//
// A leaf file with no imports and no runtime reader in the app: the app imports only the TYPE, so the
// meanings stay out of the entry bundle. The playground, `KEYS.md` (`bun scripts/glyph-keys.ts`) and
// the tests read the table itself.
//
// NOT HERE, and the same under every set: the agent logos (`AgentIcon`), the Collie mark and the
// characters, the Wordmark, the multiplexer logo, the files under `web/public`, the walky talky radio
// (`WalkyIcon`), the five status shapes (`StatusDot`) and the unseen mark (`UnseenMark`).
//
// ADDING A KEY is one row here, one in `lucide.ts`, and one in each family map under `sets/` (a
// family that has no fitting glyph says `null`, and the key draws its lucide glyph there).

