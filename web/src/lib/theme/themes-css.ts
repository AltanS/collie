// The writer of `web/src/themes.css`, kept apart from the script that calls it.
//
// `scripts/build-themes.ts` does the file reading and writing; this module turns the shipped theme
// files into the stylesheet text, as a pure function. The theme test calls the same function and
// compares the result with the file on disk, so a stale `themes.css` fails the web suite and not
// only the script's `--check`.
//
// The default theme `collie` writes NO block. Its values are the `:root` tokens in index.css, held
// equal by `src/themes/themes.test.ts`, so applying it needs no attribute and no property. Every
// other shipped theme writes one `:root[data-theme="<id>"]` block with all tokens, each half filled
// from `collie` where the file leaves a token out, and then the declarations of the shape words its
// `surface` block names, its display face and its terminal palette (surface.ts `versionTwoDeclarations`).
// A theme with none of the three writes no shape line, so a version 1 file writes exactly what it
// wrote before version 2.

import {
  DEFAULT_THEME_ID,
  OPTIONAL_THEME_TOKENS,
  THEME_TOKENS,
  fillHalves,
  lightDark,
  parseTheme,
  setsOptionalToken,
  type Theme,
} from "./schema";
import { versionTwoDeclarations } from "./surface";

/** One shipped theme file: its file name (`nightwatch.json`) and its text. */
export interface ThemeFile {
  name: string;
  raw: string;
}

export type ThemesCss = { ok: true; css: string } | { ok: false; errors: string[] };

/** Shipped files are ours, but the same import cap keeps them honest. */
const SHIPPED_MAX_BYTES = 64 * 1024;

export const THEMES_CSS_HEADER = "/* generated by scripts/build-themes.ts, do not edit */\n";

/** Validate every shipped file and write the stylesheet, or list every reason it cannot be written. */
export function buildThemesCss(files: readonly ThemeFile[]): ThemesCss {
  const errors: string[] = [];
  const themes: Theme[] = [];
  for (const file of files) {
    const parsed = parseTheme(file.raw, { maxBytes: SHIPPED_MAX_BYTES, allowReservedId: true });
    if (!parsed.ok) {
      for (const r of parsed.refusals) errors.push(`${file.name}: ${r.path}: ${r.detail}`);
      continue;
    }
    if (file.name !== `${parsed.theme.id}.json`) {
      errors.push(`${file.name}: the file must be named after its id, ${parsed.theme.id}.json`);
      continue;
    }
    themes.push(parsed.theme);
  }

  const base = themes.find((t) => t.id === DEFAULT_THEME_ID);
  if (base === undefined) {
    errors.push(`${DEFAULT_THEME_ID}.json: missing or refused; every other theme is filled from it`);
  } else {
    for (const token of THEME_TOKENS) {
      if (base.light?.[token] === undefined || base.dark?.[token] === undefined) {
        errors.push(`${DEFAULT_THEME_ID}.json: "${token}" needs a value in both halves`);
      }
    }
  }
  if (errors.length > 0 || base === undefined) return { ok: false, errors };

  const blocks = themes
    .filter((t) => t.id !== DEFAULT_THEME_ID)
    .toSorted((a, b) => (a.id < b.id ? -1 : 1))
    .map((theme) => {
      const filled = fillHalves(theme, base);
      const lines = THEME_TOKENS.map((token) => `  --${token}: ${lightDark(filled, token)};`);
      // An optional token writes a line only for a theme that names it: the rest keep index.css's pair.
      for (const token of OPTIONAL_THEME_TOKENS) {
        if (setsOptionalToken(theme, token)) lines.push(`  --${token}: ${lightDark(filled, token)};`);
      }
      for (const [property, value] of versionTwoDeclarations(theme)) lines.push(`  ${property}: ${value};`);
      return `\n:root[data-theme="${theme.id}"] {\n${lines.join("\n")}\n}\n`;
    });
  return { ok: true, css: THEMES_CSS_HEADER + blocks.join("") };
}
